import { expect, test } from '@playwright/test'

test('manages a real resume, saves editor changes and checks its history', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('link', { name: 'Open resume library' }).click()
  await page.getByRole('button', { name: 'New resume' }).first().click()
  const create = page.getByRole('dialog', { name: 'Create resume' })
  await create.getByLabel('Resume title').fill('Synthetic engineering draft')
  await create.getByRole('button', { name: 'Create resume' }).click()
  await expect(page.getByRole('heading', { name: 'Synthetic engineering draft' })).toBeVisible()
  await page.getByRole('link', { name: 'Edit resume' }).click()
  await page.getByLabel('Full name', { exact: true }).fill('Example Candidate')
  await expect(page.getByRole('status')).toContainText('Saved · Draft 2')
  await page.getByRole('navigation', { name: 'Resume sections' }).getByRole('button', { name: 'Experience', exact: true }).click()
  await page.getByRole('button', { name: 'Add item to experience' }).click()
  await page.getByLabel('Organization', { exact: true }).fill('Example Studio')
  await page.getByLabel('Position', { exact: true }).fill('Engineering Intern')
  await expect(page.getByRole('status')).toContainText('Saved · Draft 3')
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(page.getByLabel('Position', { exact: true })).toHaveValue('')
  await page.getByRole('button', { name: 'Redo', exact: true }).click()
  await expect(page.getByLabel('Position', { exact: true })).toHaveValue('Engineering Intern')
  await page.getByRole('button', { name: 'Presentation', exact: true }).click()
  await page.getByRole('combobox', { name: 'Template', exact: true }).selectOption('compact')
  await expect(page.getByRole('status')).toContainText('Saved · Draft 4')
  await page.reload()
  await expect(page.getByLabel('Full name', { exact: true })).toHaveValue('Example Candidate')
  await page.getByRole('link', { name: 'Resume history' }).click()
  await page.getByRole('button', { name: 'Save checkpoint' }).click()
  await page.getByLabel('Change summary (optional)').fill('First draft')
  await page.getByRole('dialog').getByRole('button', { name: 'Save checkpoint' }).click()
  await expect(page.getByText('First draft', { exact: false })).toBeVisible()
  await page.getByRole('combobox', { name: 'Export source', exact: true }).selectOption({ label: 'Version 1' })
  await page.getByRole('button', { name: 'Generate export' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Generate', exact: true }).click()
  const downloadLink = page.getByRole('link', { name: 'Download PDF', exact: true })
  await expect(downloadLink).toBeVisible()
  const download = page.waitForEvent('download')
  await downloadLink.click()
  expect((await download).suggestedFilename()).toBe('resume-r4.pdf')
  await page.getByRole('dialog').getByRole('button', { name: 'Done' }).click()
  await page.getByRole('link', { name: 'My resumes', exact: true }).first().click()
  await page.getByRole('button', { name: 'Rename Synthetic engineering draft' }).click()
  await page.getByRole('dialog').getByLabel('Resume title').fill('Synthetic internship draft')
  await page.getByRole('dialog').getByRole('button', { name: 'Rename resume' }).click()
  await expect(page.getByRole('link', { name: 'Synthetic internship draft' })).toBeVisible()
  await page.getByRole('button', { name: 'Duplicate Synthetic internship draft' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Duplicate resume' }).click()
  await expect(page.getByRole('heading', { name: 'Synthetic internship draft (copy)' })).toBeVisible()
  await page.getByRole('link', { name: 'My resumes', exact: true }).first().click()
  await page.getByRole('button', { name: 'Delete Synthetic internship draft (copy)', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel' }).click()
  await expect(page.getByRole('link', { name: 'Synthetic internship draft (copy)' })).toBeVisible()
  await page.getByRole('button', { name: 'Delete Synthetic internship draft (copy)', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Delete resume' }).click()
  await expect(page.getByRole('link', { name: 'Synthetic internship draft (copy)' })).toHaveCount(0)
})

test('preserves unsaved local edits after a real revision conflict', async ({ page }) => {
  await page.goto('/workspace/resumes')
  const result = await page.request.post('/api/v1/resumes', { data: { title: 'Synthetic conflict' } })
  expect(result.status()).toBe(201)
  const created = await result.json()
  const endpoint = '/api/v1/resumes/' + created.id
  await page.goto('/workspace/resumes/' + created.id + '/edit')
  await expect(page.getByLabel('Resume title')).toHaveValue('Synthetic conflict')
  const writer = await page.request.patch(endpoint, { data: { expected_revision: 1, title: 'Saved elsewhere' } })
  expect(writer.ok()).toBeTruthy()
  await page.getByLabel('Resume title').fill('Unsaved working title')
  await expect(page.getByRole('status')).toContainText('Revision conflict')
  await expect(page.getByLabel('Resume title')).toHaveValue('Unsaved working title')
  await page.getByRole('link', { name: 'Resume history' }).click()
  await expect(page.getByRole('dialog', { name: 'Leave editor?' })).toBeVisible()
  await page.getByRole('button', { name: 'Keep editing' }).click()
  await page.getByRole('button', { name: 'Load latest draft' }).click()
  await page.getByRole('button', { name: 'Load saved draft' }).click()
  await expect(page.getByLabel('Resume title')).toHaveValue('Saved elsewhere')
})

test('supports responsive navigation and backend errors', async ({ page }) => {
  for (const width of [375, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/workspace/resumes')
    await expect(page.getByRole('heading', { name: 'My resumes' })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
    if (width === 375) {
      await page.getByRole('button', { name: 'Open navigation' }).click()
      await expect(page.getByRole('navigation', { name: 'Workspace' })).toBeVisible()
      await page.getByRole('button', { name: 'Close navigation' }).click()
      await expect(page.getByRole('navigation', { name: 'Workspace' })).toBeHidden()
    }
  }
  await page.route('**/api/v1/resumes?*', (route) => route.fulfill({
    status: 503, json: { error: { code: 'DEVELOPMENT_IDENTITY_UNAVAILABLE' } },
  }))
  await page.reload()
  await expect(page.getByRole('alert')).toContainText('local workspace owner is unavailable')
  await expect(page.getByRole('link', { name: 'Workspace setup' })).toBeVisible()
  await page.getByRole('button', { name: 'Use dark theme' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
})


