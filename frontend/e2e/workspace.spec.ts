test('runs and reopens an explainable analysis of a saved checkpoint', async ({ page }) => {
  await page.goto('/workspace/analyzer')
  const resume = await page.request.post('/api/v1/resumes', {
    data: { title: 'Analyzer test resume', content: { skills: [{ name: 'Python' }] } },
  })
  expect(resume.status()).toBe(201)
  const resumeId = (await resume.json()).id
  const version = await page.request.post('/api/v1/resumes/' + resumeId + '/versions', { data: { expected_revision: 1 } })
  expect(version.status()).toBe(201)
  const job = await page.request.post('/api/v1/jobs', {
    data: { title: 'Analyzer target job', company: 'Example Works', description: 'Required: Python or Java. Preferred: AWS.' },
  })
  expect(job.status()).toBe(201)
  await page.reload()
  await page.getByRole('combobox', { name: 'Resume', exact: true }).selectOption(resumeId)
  await page.getByRole('combobox', { name: 'Resume source' }).selectOption({ label: 'Version 1' })
  await page.getByRole('combobox', { name: 'Target job' }).selectOption((await job.json()).id)
  await page.getByRole('button', { name: 'Run analysis' }).click()
  await expect(page.getByRole('heading', { name: 'Document readability' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Job compatibility' })).toBeVisible()
  await expect(page.getByText('Python or Java', { exact: true })).toBeVisible()
  await expect(page.getByText('preferred · not evidenced')).toBeVisible()
  if (process.env.HIRESENSE_CAPTURE_DOCS === '1') {
    await page.setViewportSize({ width: 1440, height: 960 })
    await page.screenshot({ path: '../docs/images/resume-analyzer.png', fullPage: true })
  }
  const analysis = await page.getByRole('combobox', { name: 'Analysis', exact: true }).inputValue()
  await page.reload()
  await page.getByRole('combobox', { name: 'Analysis', exact: true }).selectOption(analysis)
  await expect(page.getByRole('heading', { name: 'Skill evidence' })).toBeVisible()
})

test('labels and applies a mock summary proposal only after review', async ({ page }) => {
  await page.goto('/workspace/resumes')
  const created = await page.request.post('/api/v1/resumes', {
    data: { title: 'Writing review', content: { professional_summary: 'Writes   clear software.' } },
  })
  expect(created.status()).toBe(201)
  await page.goto('/workspace/resumes/' + (await created.json()).id + '/edit?section=professional_summary')
  const summary = page.getByRole('textbox', { name: /Professional summary/i })
  await expect(summary).toHaveValue('Writes   clear software.')
  await page.getByRole('button', { name: 'Review summary suggestion' }).click()
  let dialog = page.getByRole('dialog', { name: 'Summary suggestion' })
  await expect(dialog.getByText('Mock suggestion', { exact: false })).toBeVisible()
  await dialog.getByRole('button', { name: 'Reject' }).click()
  await expect(summary).toHaveValue('Writes   clear software.')
  await page.getByRole('button', { name: 'Review summary suggestion' }).click()
  dialog = page.getByRole('dialog', { name: 'Summary suggestion' })
  await dialog.getByRole('button', { name: 'Apply to draft' }).click()
  await expect(summary).toHaveValue('Writes clear software.')
  await expect(page.getByRole('status')).toContainText('Saved · Draft 2')
})

